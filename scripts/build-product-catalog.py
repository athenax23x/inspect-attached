def main() -> int:
    images = {x["image"] for x in PRODUCTS}
    skus = [x["sku"] for x in PRODUCTS]
    assert len(skus) == len(set(skus)), "SKU duplikat"

    OUT.write_text(json.dumps(PRODUCTS, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{len(PRODUCTS)} produk, {len(images)} gambar unik -> {OUT}")

    counts = {}
    for item in PRODUCTS:
        for cat in item["categories"]:
            counts[cat] = counts.get(cat, 0) + 1
    print("\nProduk per kategori:")
    for cat in sorted(counts):
        flag = "  <-- masih tipis" if counts[cat] < 2 else ""
        print(f"  {cat:26} {counts[cat]}{flag}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
